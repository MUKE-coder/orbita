package build

import "github.com/orbita-sh/orbita/internal/grit"

// GenerateDockerfile produces a production Dockerfile for a Grit service,
// matching the shapes of the files Grit already ships (grit-knowledge/04).
//
// This is a FALLBACK only: Orbita reuses the repo's committed Dockerfiles. Use
// this when one is genuinely missing (a hand-written or older Grit app), e.g.
// the CLI's repo-prep step commits it before the first deploy. It deliberately
// mirrors the shipped files' key properties: CGO_ENABLED=0, -ldflags="-s -w",
// non-root user, and `chown -R` before `USER` (the embedded Pulse/Sentinel
// SQLite stores need write access under /app).
func GenerateDockerfile(role string) (string, bool) {
	switch role {
	case grit.RoleAPI:
		return apiDockerfile, true
	case grit.RoleApp:
		return singleDockerfile, true
	case grit.RoleWeb, grit.RoleAdmin, grit.RoleDocs:
		return nextjsDockerfile(role), true
	default:
		return "", false
	}
}

const apiDockerfile = `# Generated by Orbita (fallback) — matches Grit's shipped apps/api/Dockerfile.
FROM golang:1.24-alpine AS builder
WORKDIR /app
COPY go.mod go.sum ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -ldflags="-s -w" -o /app/server ./cmd/server

FROM alpine:3.19
RUN apk --no-cache add ca-certificates tzdata
RUN addgroup -S app && adduser -S -G app app
WORKDIR /app
COPY --from=builder /app/server .
# chown before USER: embedded Pulse/Sentinel SQLite stores need write access.
RUN chown -R app:app /app
USER app
EXPOSE 8080
CMD ["./server"]
`

const singleDockerfile = `# Generated by Orbita (fallback) — matches Grit's shipped single-mode Dockerfile.
FROM node:22-alpine AS frontend
RUN corepack enable && corepack prepare pnpm@9.15.0 --activate
WORKDIR /app/frontend
COPY frontend/package.json frontend/pnpm-lock.yaml ./
RUN pnpm install --frozen-lockfile
COPY frontend/ ./
RUN pnpm build

FROM golang:1.24-alpine AS builder
WORKDIR /app
COPY go.mod go.sum ./
RUN go mod download
COPY . .
COPY --from=frontend /app/frontend/dist ./frontend/dist
RUN CGO_ENABLED=0 GOOS=linux go build -ldflags="-s -w" -o /app/server .

FROM alpine:3.19
RUN apk --no-cache add ca-certificates tzdata
RUN addgroup -S app && adduser -S -G app app
WORKDIR /app
COPY --from=builder /app/server .
RUN chown -R app:app /app
USER app
EXPOSE 8080
CMD ["./server"]
`

// nextjsDockerfile matches Grit's shipped web/admin/docs Dockerfiles: a pnpm
// workspace build from the repo root producing Next.js standalone output.
func nextjsDockerfile(role string) string {
	return `# Generated by Orbita (fallback) — matches Grit's shipped apps/` + role + `/Dockerfile.
# Build context is the REPO ROOT (needs root package.json, pnpm-workspace.yaml, packages/shared).
FROM node:22-alpine AS deps
RUN corepack enable && corepack prepare pnpm@9.15.0 --activate
WORKDIR /app
COPY package.json pnpm-lock.yaml pnpm-workspace.yaml ./
COPY apps/` + role + `/package.json apps/` + role + `/package.json
COPY packages ./packages
RUN pnpm install --frozen-lockfile

FROM node:22-alpine AS builder
RUN corepack enable && corepack prepare pnpm@9.15.0 --activate
WORKDIR /app
ARG NEXT_PUBLIC_API_URL
ENV NEXT_PUBLIC_API_URL=$NEXT_PUBLIC_API_URL
COPY --from=deps /app/node_modules ./node_modules
COPY . .
RUN pnpm --filter ./apps/` + role + ` build

FROM node:22-alpine AS runner
WORKDIR /app
RUN addgroup -S app && adduser -S -G app app
ENV NODE_ENV=production
COPY --from=builder /app/apps/` + role + `/.next/standalone ./
COPY --from=builder /app/apps/` + role + `/.next/static ./apps/` + role + `/.next/static
COPY --from=builder /app/apps/` + role + `/public ./apps/` + role + `/public
RUN chown -R app:app /app
USER app
EXPOSE 3000
CMD ["node", "apps/` + role + `/server.js"]
`
}
